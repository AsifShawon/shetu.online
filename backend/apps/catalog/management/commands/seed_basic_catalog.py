class Command(BaseCommand):
    help = "Seed basic catalog data for countries, service categories, and study levels."

    def handle(self, *args, **options):
        country_created = 0
        service_created = 0
        level_created = 0

        for name in COUNTRIES:
            _, created = Country.objects.update_or_create(
                name=name,
                defaults={
                    "slug": slugify(name),
                    "status": "active",
                },
            )
            country_created += int(created)

        for name in SERVICE_CATEGORIES:
            _, created = ServiceCategory.objects.update_or_create(
                name=name,
                defaults={
                    "description": "",
                    "status": "active",
                },
            )
            service_created += int(created)

        for name in STUDY_LEVELS:
            _, created = StudyLevel.objects.update_or_create(
                name=name,
                defaults={
                    "slug": slugify(name),
                    "status": "active",
                },
            )
            level_created += int(created)

        self.stdout.write(
            self.style.SUCCESS(
                f"Catalog seeded. Countries: {Country.objects.count()} total ({country_created} new), "
                f"Services: {ServiceCategory.objects.count()} total ({service_created} new), "
                f"Study Levels: {StudyLevel.objects.count()} total ({level_created} new)."
            )
        )
